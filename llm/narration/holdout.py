def holdout_scenarios() -> list[Scenario]:
    scenarios = []
    for index, (rule, code, track, condition, duration, banded, action, extra) in enumerate(_ROWS):
        scenarios.append(
            Scenario(
                scenario_id=f"holdout-{rule}-{index:03d}",
                split="holdout",
                rule_id=rule,
                action_code=code,
                source_run="run-holdout",
                condition_family=-1,
                action_family=-1,
                request=WordingRequest(
                    observed_subject=f"Worker {track}",
                    observed_condition=condition,
                    duration_s=duration,
                    relative_band=DistanceBand.NEAR if banded else None,
                    deterministic_action=action,
                    allowed_entities=(track, *extra),
                ),
            )
        )
    return scenarios
